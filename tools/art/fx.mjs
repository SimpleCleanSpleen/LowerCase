export const FONT_CHARS = Object.keys(GLYPHS).join('');
const CW = 7;
const CH = 9;
const PER_ROW = 16;

function buildFont(root) {
  const chars = [...FONT_CHARS];
  const rows = Math.ceil(chars.length / PER_ROW);
  const cv = new RgbCanvas(PER_ROW * CW, rows * CH);
  const white = [255, 255, 255];
  const dark = [20, 14, 30];
  chars.forEach((ch, i) => {
    const ox = (i % PER_ROW) * CW + 1;
    const oy = Math.floor(i / PER_ROW) * CH + 1;
    const g = GLYPHS[ch];
    const on = (x, y) => y >= 0 && y < 7 && x >= 0 && x < 5 && g[y][x] === '#';
    for (let y = -1; y <= 7; y++)
      for (let x = -1; x <= 5; x++) {
        if (on(x, y)) cv.set(ox + x, oy + y, y >= 5 ? [200, 200, 220] : white);
        else if (on(x + 1, y) || on(x - 1, y) || on(x, y + 1) || on(x, y - 1) || on(x - 1, y - 1)) cv.set(ox + x, oy + y, dark);
      }
  });
  const dir = join(root, 'public/assets/ui');
  writeFile(join(dir, 'font.png'), cv.png());
  writeFile(join(dir, 'font.json'), `${JSON.stringify({ width: CW, height: CH, chars: FONT_CHARS, charsPerRow: PER_ROW })}\n`);
}

// --------------------------------------------------------------- effects --
// One sheet of 32x32 cells; rows = effects, columns = frames.

export const FX = { cell: 32, flame: 0, hit: 1, block: 2, dust: 3, wave: 4, spark: 5 };

function buildFx(root) {
  const S = FX.cell;
  const cv = new RgbCanvas(S * 6, S * 6);
  const R = rng(99);
  const at = (row, col) => [col * S, row * S];

  // torch flames: 4 frames, base at the bottom-center of the cell
  for (let f = 0; f < 4; f++) {
    const [ox, oy] = at(FX.flame, f);
    const sway = [0, 1, 0, -1][f];
    const h = [14, 16, 13, 15][f];
    for (const [w, c, hh] of [[5, '#e0401a', 1], [3.6, '#ff9a2a', 0.8], [2, '#ffe8a0', 0.55]]) {
      const top = 30 - h * hh;
      cv.poly([[ox + 16 - w, oy + 30], [ox + 16 - w * 0.7 + sway, oy + 30 - h * hh * 0.5], [ox + 16 + sway * 2, oy + top], [ox + 16 + w * 0.7 + sway, oy + 30 - h * hh * 0.5], [ox + 16 + w, oy + 30]], hex(c));
    }
  }

  // hit sparks (white/yellow star burst) & block sparks (blue)
  const burst = (row, cols) => {
    for (let f = 0; f < 4; f++) {
      const [ox, oy] = at(row, f);
      const cx = ox + 16;
      const cy = oy + 16;
      const r = [6, 12, 15, 14][f];
      const rays = 8;
      for (let k = 0; k < rays; k++) {
        const a = (k / rays) * Math.PI * 2 + f * 0.2;
        const len = r * (k % 2 ? 0.6 : 1);
        const w = f === 3 ? 0.8 : 1.6;
        const nx = Math.cos(a);
        const ny = Math.sin(a);
        cv.poly([[cx - ny * w, cy + nx * w], [cx + nx * len, cy + ny * len], [cx + ny * w, cy - nx * w]], hex(f === 3 ? cols[2] : cols[1]));
      }
      if (f < 3) cv.disc(cx, cy, [4, 5, 3][f], hex(cols[0]));
    }
  };
  burst(FX.hit, ['#ffffff', '#ffe060', '#ff8a2a']);
  burst(FX.block, ['#ffffff', '#a0d8ff', '#4a8aff']);

  // dust puffs
  for (let f = 0; f < 4; f++) {
    const [ox, oy] = at(FX.dust, f);
    for (let k = 0; k < 5; k++) {
      const x = ox + 6 + k * 5 + f * (k - 2) * 0.8;
      const y = oy + 26 - f * 2 - (k % 2) * 2;
      cv.disc(x, y, 4 - f * 0.8, hex(f < 2 ? '#c8b8a8' : '#988878'), 230 - f * 50);
    }
  }

  // projectile: glowing sigil, white/greyscale so it can be tinted per skin
  for (let f = 0; f < 4; f++) {
    const [ox, oy] = at(FX.wave, f);
    const cx = ox + 16;
    const cy = oy + 16;
    cv.disc(cx - 4, cy, 12 + (f % 2), [140, 140, 140], 90);
    for (let k = 0; k < 6; k++) cv.disc(cx - 8 - k * 2 - R() * 3, cy + (R() - 0.5) * 12, 1.5, [200, 200, 200], 160);
    const P = (x, y) => [cx + x, cy + y];
    cv.poly([P(-7, -8), P(7, -8), P(7, 1), P(0, 9), P(-7, 1)], [255, 255, 255]);
    cv.poly([P(-5, -6), P(5, -6), P(5, 0.5), P(0, 6.5), P(-5, 0.5)], [170, 170, 170]);
    cv.poly([P(0, -4), P(4, 0.5), P(4, 3), P(0, -1.5), P(-4, 3), P(-4, 0.5)], [255, 255, 255]);
  }

  // charge sparkle (tiny 4-point star)
  for (let f = 0; f < 4; f++) {
    const [ox, oy] = at(FX.spark, f);
    const r = [2, 4, 3, 1][f];
    cv.rect(ox + 16 - r, oy + 16, r * 2 + 1, 1, [255, 255, 255]);
    cv.rect(ox + 16, oy + 16 - r, 1, r * 2 + 1, [255, 255, 255]);
  }

  // clean emblem (title screen): the sigil alone, white for tinting
  {
    const [ox, oy] = at(FX.spark, 4);
    const P = (x, y) => [ox + 16 + x * 1.6, oy + 16 + y * 1.6];
    cv.poly([P(-7, -8), P(7, -8), P(7, 1), P(0, 9), P(-7, 1)], [255, 255, 255]);
    cv.poly([P(-5.5, -6.5), P(5.5, -6.5), P(5.5, 0.5), P(0, 7.2), P(-5.5, 0.5)], [150, 150, 150]);
    cv.poly([P(0, -4.5), P(4.5, 0.5), P(4.5, 3.2), P(0, -1.4), P(-4.5, 3.2), P(-4.5, 0.5)], [255, 255, 255]);
  }

  writeFile(join(root, 'public/assets/ui/fx.png'), cv.png());
}

export function buildUi(root) {
  buildFont(root);
  buildFx(root);
}
